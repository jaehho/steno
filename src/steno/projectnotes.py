"""A meeting's summary and transcript, kept in the project it was about.

A meeting whose project (meta.json) is P, a directory under the projects
root, is written to `P/notes/meetings/`:

    README.md                                     index, newest first
    .gitignore                                    made with the folder
    2026-10-06-1612-rcnn-toolbox.md               summary, to-dos, notes
    2026-10-06-1612-rcnn-toolbox.transcript.md    what was said

so that whoever opens the project, a person or an agent, finds the
meetings it had. Nothing here reaches a network or a model.

The folder may be synced and the repository pushed, and that sets the
rules. Steno writes inside the project only: a name that is not a plain
directory directly under the root, or a path that resolves out of the
project (a symlinked `notes`), is refused. It replaces only a file it
wrote, which says so on its first line after the front matter; any other
file is left as it is and reported. A file is written when its bytes
would change, whole (a temp file, then a rename). Transcripts are other
people's speech, so the `.gitignore` made with the folder ignores all.

meta.json keeps a `published` record, the project and the file names, so
that a new title, a new project or a deleted meeting takes away what an
earlier run wrote. `STENO_PROJECT_NOTES=0` turns the whole thing off.
"""
from __future__ import annotations

import json
import logging
import os
import re
import secrets
import threading
from collections.abc import Iterable, Mapping
from dataclasses import dataclass, field
from datetime import date, datetime
from pathlib import Path
from typing import Literal, NamedTuple

from . import export
from .notes import open_count
from .summarize import (
    duration_minutes,
    load_meta,
    load_project,
    load_records,
    load_title,
    projects_root,
    update_meta,
)

log = logging.getLogger(__name__)

SWITCH_ENV = "STENO_PROJECT_NOTES"
RECORD_KEY = "published"
INDEX_NAME = "README.md"
GITIGNORE_NAME = ".gitignore"
TRANSCRIPT_SUFFIX = ".transcript.md"
UNTITLED = "Untitled meeting"
# A title is words; a file name is not allowed to be a paragraph.
MAX_SLUG = 60
# Opens the line after the front matter that says steno wrote a file.
MARKER_PREFIX = "<!-- Generated by steno"

GITIGNORE = """\
# Written by steno when it made this folder. The transcripts in it are
# other people's speech, so nothing here is committed. Delete this file to
# make the meetings committable; steno will not write it again.
*
!.gitignore
"""

INDEX_INTRO = """\
# Meetings

Summaries and transcripts of the meetings steno recorded that were
about this project, newest first. Each meeting is a summary page with a
`.transcript.md` page beside it.

Steno writes and overwrites everything here, so edit nothing: a file
that lacks the generated-by line at its top is yours and is left alone.
The `.gitignore` made with this folder keeps the transcripts, which are
other people's speech, out of git; delete it to commit them."""

# Words YAML would read as something other than text, if left bare.
_YAML_WORDS = frozenset(
    {"true", "false", "yes", "no", "on", "off", "null", "y", "n"}
)
_BARE_RE = re.compile(r"[a-z][a-z0-9_-]*\Z")

Action = Literal["create", "update", "same", "remove", "skip"]
Scalar = str | int | date


class Change(NamedTuple):
    """What was done to one path; with a dry run, what would be."""

    action: Action
    path: Path
    note: str = ""


@dataclass
class Result:
    """What a publish or an unpublish did.

    `project` is where the meeting is filed (meta.json), whether or not
    anything could be written there. `note` says why nothing was, and
    is "" when the work went ahead. `changes` lists each path looked at:
    `same` for a file that already has the right bytes, `skip` (with a
    note) for one that is not steno's to touch.
    """

    project: str | None
    changes: list[Change] = field(default_factory=list)
    note: str = ""

    @property
    def altered(self) -> list[Change]:
        """The changes that write or remove something."""
        return [
            c for c in self.changes
            if c.action in ("create", "update", "remove")
        ]

    @property
    def skipped(self) -> list[Change]:
        return [c for c in self.changes if c.action == "skip"]


class Record(NamedTuple):
    """What meta.json says a meeting has published, and where."""

    project: str
    files: tuple[str, ...]


class Entry(NamedTuple):
    """One meeting's line in a project's index."""

    name: str
    title: str
    date: str
    time: str
    minutes: int
    open_todos: int


@dataclass(frozen=True)
class Meeting:
    """What the pages of one meeting are made from."""

    session: str
    when: datetime
    title: str | None
    minutes: int
    open_todos: int
    body: str  # the export page, without its transcript section
    transcript: str  # `[mm:ss] who: text` lines; "" if nothing was said


_LOCK = threading.RLock()


def enabled() -> bool:
    """False when `STENO_PROJECT_NOTES` is set to anything but a yes.

    Unset or empty is on. Anything else that is not a plain yes is off:
    a switch that keeps transcripts out of a folder fails to the side
    that writes nothing.
    """
    value = os.environ.get(SWITCH_ENV, "").strip().lower()
    return value in ("", "1", "true", "yes", "on")


# --- naming -----------------------------------------------------------


def page_stem(
    when: datetime, title: str | None, *, seconds: bool = False
) -> str:
    """`2026-10-06-1612-rcnn-toolbox`: the minute the meeting began and
    its title. With `seconds` the stamp runs to the second, for a
    meeting whose minute and title another meeting already has."""
    stamp = when.strftime("%Y-%m-%d-%H%M%S" if seconds else "%Y-%m-%d-%H%M")
    slug = export.title_slug(title or "")[:MAX_SLUG].strip("-")
    return f"{stamp}-{slug}" if slug else stamp


def _plain_name(name: str) -> bool:
    """A single path component that is not hidden."""
    return (
        bool(name)
        and name == Path(name).name
        and not name.startswith(".")
        and "\0" not in name
    )


def _is_page_name(name: str) -> bool:
    """A name steno gives a file: plain, `.md`."""
    return _plain_name(name) and name.endswith(".md")


def _is_summary_name(name: str) -> bool:
    return (
        _is_page_name(name)
        and name != INDEX_NAME
        and not name.endswith(TRANSCRIPT_SUFFIX)
    )


def project_dir(root: Path, project: str) -> Path:
    """`root/project`, if `project` is the plain name of a directory
    directly under `root`.

    Raises ValueError saying what is wrong. The directory is never
    made: a project steno was told of that is not there is not steno's
    to create. A project that is itself a symlink is followed, since the
    projects listing does.
    """
    if not _plain_name(project):
        msg = f"not a project directory name: {project!r}"
        raise ValueError(msg)
    path = root / project
    if not path.is_dir():
        msg = f"no such project: {path}"
        raise ValueError(msg)
    return path


def meetings_dir(project: Path) -> Path:
    """Where the project's meetings go, resolved through symlinks.

    Raises ValueError when that is not inside the project (a symlinked
    `notes` or `meetings` pointing out), or is a file. The folder may
    not exist yet; everything later is done on this resolved path.
    """
    try:
        base = project.resolve()
        folder = (base / "notes" / "meetings").resolve()
    except (OSError, RuntimeError) as err:
        msg = f"cannot resolve {project}: {err}"
        raise ValueError(msg) from err
    if not folder.is_relative_to(base):
        msg = f"{base / 'notes' / 'meetings'} leads out of {base}"
        raise ValueError(msg)
    if folder.exists() and not folder.is_dir():
        msg = f"{folder} is not a directory"
        raise ValueError(msg)
    return folder


# --- the text of a page -----------------------------------------------


def _scalar(value: Scalar) -> str:
    """A front matter value: a date or number as it is, a plain word
    bare, any other text as a JSON string, which YAML reads as one."""
    if isinstance(value, date):
        return value.isoformat()
    if isinstance(value, int):
        return str(value)
    if _BARE_RE.match(value) and value not in _YAML_WORDS:
        return value
    return json.dumps(value, ensure_ascii=False)


def frontmatter(fields: Mapping[str, Scalar]) -> str:
    """`---`, a `key: value` line for each field, `---`."""
    lines = [f"{key}: {_scalar(value)}" for key, value in fields.items()]
    return "\n".join(["---", *lines, "---"])


def _field(raw: str) -> str | int:
    try:
        value = json.loads(raw)
    except ValueError:
        return raw  # a bare word or a date
    return value if isinstance(value, str | int) else raw


def _split_page(text: str) -> tuple[dict[str, str | int], list[str]]:
    """A page as its front matter fields and the lines after them."""
    lines = [line.rstrip("\r") for line in text.split("\n")]
    if lines[0].strip() != "---":
        return {}, lines
    for end in range(1, len(lines)):
        if lines[end].strip() == "---":
            fields = {}
            for line in lines[1:end]:
                key, colon, raw = line.partition(": ")
                if colon:
                    fields[key.strip()] = _field(raw.strip())
            return fields, lines[end + 1:]
    return {}, lines


def marker(session: str | None) -> str:
    """The line that says steno wrote the file under it."""
    where = f" from session {session}" if session else ""
    return f"{MARKER_PREFIX}{where}. Edits are overwritten. -->"


def is_generated(text: str) -> bool:
    """True when the first line after the front matter is steno's
    marker. A file that merely mentions it further down is not."""
    after = _split_page(text)[1]
    return next((x for x in after if x.strip()), "").startswith(
        MARKER_PREFIX
    )


def session_of(text: str) -> str:
    """The session a generated page is of, "" if it names none."""
    return str(_split_page(text)[0].get("session", ""))


def _page(fields: Mapping[str, Scalar], session: str, body: str) -> str:
    return "\n".join(
        [frontmatter(fields), marker(session), "", body.strip("\n"), ""]
    )


def summary_page(
    meeting: Meeting, project: str, transcript_name: str
) -> str:
    """The summary page: what `steno export` makes, less the words."""
    fields: dict[str, Scalar] = {
        "title": meeting.title or UNTITLED,
        "date": meeting.when.date(),
        "time": f"{meeting.when:%H:%M}",
        "duration_min": meeting.minutes,
        "project": project,
        "session": meeting.session,
        "generated_by": "steno",
        "transcript": transcript_name,
        "todos_open": meeting.open_todos,
    }
    link = f"## Transcript\n\n[{transcript_name}]({transcript_name})"
    body = f"{meeting.body.rstrip()}\n\n{link}"
    return _page(fields, meeting.session, body)


def transcript_page(meeting: Meeting, project: str) -> str:
    """The words of the meeting, stamped as the summary's refs are."""
    fields: dict[str, Scalar] = {
        "title": meeting.title or UNTITLED,
        "date": meeting.when.date(),
        "time": f"{meeting.when:%H:%M}",
        "project": project,
        "session": meeting.session,
        "generated_by": "steno",
    }
    body = f"# {meeting.title or UNTITLED}: transcript\n\n{meeting.transcript}"
    return _page(fields, meeting.session, body)


def entry_of(name: str, text: str) -> Entry | None:
    """The index line a generated summary page asks for, None for any
    other file."""
    if not is_generated(text):
        return None
    fields = _split_page(text)[0]
    if "session" not in fields:
        return None

    def count(key: str) -> int:
        value = fields.get(key, 0)
        return value if isinstance(value, int) else 0

    return Entry(
        name=name,
        title=str(fields.get("title") or UNTITLED),
        date=str(fields.get("date", "")),
        time=str(fields.get("time", "")),
        minutes=count("duration_min"),
        open_todos=count("todos_open"),
    )


def _entry_line(entry: Entry) -> str:
    title = " ".join(entry.title.split())
    title = title.replace("[", r"\[").replace("]", r"\]")
    parts = [f"{entry.date} {entry.time}".strip(), f"[{title}]({entry.name})"]
    if entry.minutes >= 1:
        parts.append(f"{entry.minutes} min")
    if entry.open_todos:
        many = "" if entry.open_todos == 1 else "s"
        parts.append(f"{entry.open_todos} open to-do{many}")
    return "- " + " · ".join(parts)


def index_page(entries: Iterable[Entry]) -> str:
    """The folder's README: a line per meeting, newest first. The same
    entries give the same bytes."""
    ordered = sorted(
        entries, key=lambda e: (e.date, e.time, e.name), reverse=True
    )
    lines = [marker(None), "", INDEX_INTRO, ""]
    lines += [_entry_line(e) for e in ordered]
    return "\n".join(lines) + "\n"


# --- what a meeting is ------------------------------------------------


def session_time(session_dir: Path) -> datetime:
    """When the meeting began, from the directory's name.

    The name never changes. A start time worked out from the audio
    does, once the audio is pruned, and a file name made from it would
    move.
    """
    try:
        return datetime.strptime(session_dir.name[:15], "%Y%m%d-%H%M%S")
    except ValueError:
        return export.session_datetime(session_dir)


def load_meeting(session_dir: Path) -> Meeting:
    records = load_records(session_dir)
    title = load_title(session_dir)
    return Meeting(
        session=session_dir.name,
        when=session_time(session_dir),
        title=title if isinstance(title, str) and title else None,
        minutes=round(duration_minutes(records)),
        open_todos=open_count(session_dir),
        body=export.meeting_markdown(session_dir, transcript=False),
        transcript=export.transcript_text(session_dir, records),
    )


def read_record(session_dir: Path) -> Record | None:
    """The `published` record in meta.json, None if there is none or it
    is damaged."""
    raw = load_meta(session_dir).get(RECORD_KEY)
    if not isinstance(raw, dict):
        return None
    project, files = raw.get("project"), raw.get("files")
    if not isinstance(project, str) or not isinstance(files, list):
        return None
    return Record(project, tuple(f for f in files if isinstance(f, str)))


def _store_record(session_dir: Path, record: Record | None) -> None:
    if record == read_record(session_dir):
        return
    raw = None
    if record is not None:
        raw = {"project": record.project, "files": list(record.files)}
    update_meta(session_dir, **{RECORD_KEY: raw})


# --- one folder -------------------------------------------------------


class _RefusedError(Exception):
    """A path steno will not read or replace; the message says why."""


def _read(path: Path) -> bytes | None:
    """The file's bytes, None if there is no such file.

    Raises _RefusedError for a link or a directory, which steno neither
    reads nor replaces. A failing read is an OSError.
    """
    if path.is_symlink():
        msg = "is a symbolic link"
        raise _RefusedError(msg)
    if path.is_dir():
        msg = "is a directory"
        raise _RefusedError(msg)
    try:
        return path.read_bytes()
    except FileNotFoundError:
        return None


def _read_text(path: Path) -> str | None:
    """The file's text, None when it is missing or not worth reading."""
    try:
        data = _read(path)
    except (_RefusedError, OSError):
        return None
    return None if data is None else data.decode(errors="replace")


def _refusal(text: str, session: str | None) -> str:
    """Why an existing file is not steno's to replace, "" if it is. A
    page of another meeting is not, when `session` is given."""
    if not is_generated(text):
        return "not written by steno"
    if session is not None and session_of(text) != session:
        return "a page of another meeting"
    return ""


def _write_whole(path: Path, data: bytes) -> None:
    """Replace `path` with `data` all at once. The temp file is made
    new (`O_EXCL`), so it can never be a link to somewhere else."""
    tmp = path.with_name(f".{path.name}.{secrets.token_hex(4)}.tmp")
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o666)
    try:
        with os.fdopen(fd, "wb") as handle:
            handle.write(data)
        tmp.replace(path)
    except Exception:
        tmp.unlink(missing_ok=True)
        raise


class _Folder:
    """One project's `notes/meetings/`, as it is and as a run leaves it.

    Every write and removal goes through here, and only of what steno
    may touch: that is reported as a `skip`, anything else that fails
    (a full disk) is an OSError for the caller. With `dry_run` nothing
    on disk changes, but `names` and `entries` do, so the changes a dry
    run reports are the ones the real run makes. `changes` collects
    them.
    """

    def __init__(self, project: Path, dry_run: bool) -> None:
        self.dir = meetings_dir(project)
        self.dry_run = dry_run
        self.changes: list[Change] = []
        self.names = (
            {p.name for p in self.dir.iterdir()} if self.dir.is_dir()
            else set()
        )
        self.entries = self._scan()

    def _scan(self) -> dict[str, Entry]:
        found = {}
        for name in sorted(filter(_is_summary_name, self.names)):
            text = _read_text(self.dir / name)
            entry = None if text is None else entry_of(name, text)
            if entry is not None:
                found[name] = entry
        return found

    def _note(self, change: Change) -> Change:
        if change.action == "skip":
            log.warning(
                "project notes: skipped %s: %s", change.path, change.note
            )
        self.changes.append(change)
        return change

    def _holds_index(self) -> bool:
        text = _read_text(self.dir / INDEX_NAME)
        return text is not None and is_generated(text)

    def put(self, name: str, text: str, session: str | None) -> Change:
        """Create or update a file, unless it is not steno's to."""
        path = self.dir / name
        data = text.encode(errors="replace")
        try:
            old = _read(path)
        except _RefusedError as why:
            return self._note(Change("skip", path, str(why)))
        action: Action = "create"
        if old is not None:
            if why := _refusal(old.decode(errors="replace"), session):
                return self._note(Change("skip", path, why))
            action = "same" if old == data else "update"
        if action != "same" and not self.dry_run:
            self.dir.mkdir(parents=True, exist_ok=True)
            _write_whole(path, data)
        self.names.add(name)
        if _is_summary_name(name) and (entry := entry_of(name, text)):
            self.entries[name] = entry
        return self._note(Change(action, path))

    def drop(self, name: str, session: str | None) -> None:
        """Remove a file, if it is there and steno's."""
        path = self.dir / name
        if not _is_page_name(name):
            self._note(Change("skip", self.dir, f"not a page: {name!r}"))
            return
        if name not in self.names:
            return
        try:
            old = _read(path)
        except _RefusedError as why:
            self._note(Change("skip", path, str(why)))
            return
        if old is not None:
            if why := _refusal(old.decode(errors="replace"), session):
                self._note(Change("skip", path, why))
                return
            if not self.dry_run:
                path.unlink()
            self._note(Change("remove", path))
        self.names.discard(name)
        self.entries.pop(name, None)

    def add_gitignore(self) -> None:
        """Make `.gitignore` when the folder is new, and not again:
        with an index here, a missing one was deleted on purpose."""
        if GITIGNORE_NAME not in self.names and not self._holds_index():
            self.put(GITIGNORE_NAME, GITIGNORE, None)

    def stem_for(self, meeting: Meeting) -> str:
        """The file name stem for a meeting. Its minute and title, or
        its second too if another meeting's page has that name."""
        stem = page_stem(meeting.when, meeting.title)
        text = _read_text(self.dir / f"{stem}.md")
        if (
            text is not None
            and is_generated(text)
            and session_of(text) != meeting.session
        ):
            return page_stem(meeting.when, meeting.title, seconds=True)
        return stem

    def refresh_index(self) -> None:
        """Rewrite the README from the pages here; with none left,
        remove it, and the folder if that leaves it empty."""
        if self.entries:
            self.put(INDEX_NAME, index_page(self.entries.values()), None)
            return
        if self._holds_index():
            self.drop(INDEX_NAME, None)
        self._tidy()

    def _tidy(self) -> None:
        """Remove an empty folder, and the `.gitignore` made for it if
        nobody changed that."""
        if self.names != {GITIGNORE_NAME}:
            return
        path = self.dir / GITIGNORE_NAME
        try:
            if _read(path) != GITIGNORE.encode():
                return
            if not self.dry_run:
                path.unlink()
                self.dir.rmdir()
        except (_RefusedError, OSError):
            return  # a tidy-up is not worth failing a publish for
        self.names.clear()
        self._note(Change("remove", path))
        self._note(Change("remove", self.dir, "empty folder"))


# --- publishing -------------------------------------------------------


def _switched_off(force: bool) -> str:
    """Why nothing is written, if the switch says so; else ""."""
    if force or enabled():
        return ""
    return f"{SWITCH_ENV}={os.environ[SWITCH_ENV]!r}: nothing written"


def _fill(
    folder: _Folder, meeting: Meeting, project: str, previous: Record | None
) -> tuple[Record | None, frozenset[Path]]:
    """Write the meeting's two pages into `folder`, take away its stale
    ones, and bring the index up to date. Returns the record of what is
    there now and the paths of the pages."""
    stem = folder.stem_for(meeting)
    summary, words = f"{stem}.md", f"{stem}{TRANSCRIPT_SUFFIX}"
    pages = {
        summary: summary_page(meeting, project, words),
        words: transcript_page(meeting, project),
    }
    folder.add_gitignore()
    written = []
    for name, text in pages.items():
        if folder.put(name, text, meeting.session).action != "skip":
            written.append(name)
    if previous is not None and previous.project == project:
        for name in previous.files:
            if name not in written:
                folder.drop(name, meeting.session)
    folder.refresh_index()
    record = Record(project, tuple(written)) if written else None
    return record, frozenset(folder.dir / name for name in written)


def _withdraw(
    session: str,
    record: Record,
    root: Path,
    dry_run: bool,
    spare: frozenset[Path] = frozenset(),
) -> list[Change]:
    """Take what a record names out of its project, and its index line.

    `spare` are paths just written, which a project reached by a second
    name (a symlink) must not lose.
    """
    try:
        folder = _Folder(project_dir(root, record.project), dry_run)
    except ValueError as err:
        return [Change("skip", root / record.project, str(err))]
    for name in record.files:
        if folder.dir / name not in spare:
            folder.drop(name, session)
    folder.refresh_index()
    return folder.changes


def _meeting_with_words(session_dir: Path) -> Meeting:
    """The meeting to publish. Raises ValueError if nothing was said."""
    meeting = load_meeting(session_dir)
    if not meeting.transcript:
        msg = "nothing was said, so nothing to publish"
        raise ValueError(msg)
    return meeting


def _project_of(session_dir: Path) -> str | None:
    project = load_project(session_dir)
    return project if isinstance(project, str) and project else None


def publish(
    session_dir: Path,
    root: Path | None = None,
    *,
    dry_run: bool = False,
    force: bool = False,
) -> Result:
    """Make a meeting's pages in its project match the meeting.

    Safe to call again and again: a page is written when its bytes
    differ, and nothing else is touched. A new title or a new project
    takes away the files an earlier run wrote (the record in meta.json
    says which), and a meeting with no project loses them all.

    What cannot be published is reported, not raised: `Result.note`
    says why a meeting went nowhere, and a `skip` change names a file
    that is not steno's to touch. A write or removal that fails
    (OSError) is raised; the record is written last, so calling again
    finishes the job. The caller waits for a recording to be over.

    `root` is the projects directory (default `projects_root()`). With
    `dry_run` neither the project nor meta.json is written, and the
    result is what the real run would give. `force` ignores
    `STENO_PROJECT_NOTES=0`, for a person running it by hand.
    """
    root = root if root is not None else projects_root()
    with _LOCK:
        project = _project_of(session_dir)
        previous = read_record(session_dir)
        result = Result(project)
        if note := _switched_off(force):
            result.note = note
            return result
        leaving = None
        if previous is not None and previous.project != project:
            leaving = previous
        record = None if leaving or not project else previous
        spare: frozenset[Path] = frozenset()
        if project:
            try:
                meeting = _meeting_with_words(session_dir)
                folder = _Folder(project_dir(root, project), dry_run)
            except ValueError as err:
                result.note = str(err)
            else:
                record, spare = _fill(folder, meeting, project, previous)
                result.changes += folder.changes
        if leaving:
            result.changes += _withdraw(
                session_dir.name, leaving, root, dry_run, spare
            )
        if not dry_run:
            _store_record(session_dir, record)
        return result


def unpublish(
    session_dir: Path, root: Path | None = None, *, dry_run: bool = False
) -> Result:
    """Take a meeting's pages out of the project they were put in.

    Only what the record in meta.json names, and only the files that
    still say steno wrote them. Works whatever `STENO_PROJECT_NOTES`
    says: it removes, and it is asked for. A meeting about to be
    deleted is unpublished first, while its meta.json is there to say
    what it published.
    """
    root = root if root is not None else projects_root()
    with _LOCK:
        record = read_record(session_dir)
        result = Result(record.project if record else None)
        if record is None:
            result.note = "not published"
            return result
        result.changes = _withdraw(session_dir.name, record, root, dry_run)
        if not dry_run:
            _store_record(session_dir, None)
        return result


def rebuild_index(
    project: str,
    root: Path | None = None,
    *,
    dry_run: bool = False,
    force: bool = False,
) -> Result:
    """Write a project's README from the pages in its folder.

    For a folder whose README was lost or edited by hand. Does not
    make a folder that is not there.
    """
    root = root if root is not None else projects_root()
    with _LOCK:
        result = Result(project)
        if note := _switched_off(force):
            result.note = note
            return result
        try:
            folder = _Folder(project_dir(root, project), dry_run)
        except ValueError as err:
            result.note = str(err)
            return result
        if folder.names:
            folder.refresh_index()
        result.changes = folder.changes
        return result
